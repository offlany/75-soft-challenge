export type TranslationKey = keyof typeof translations;

export function getActiveLocale(): Locale {
  return activeLocale;
}

let activeLocale: Locale = "hu";

export function setLocale(locale: Locale): void {
  activeLocale = locale;
  setActiveLocale(locale);
}

export function readPreferredLocale(): Locale | null {
  if (typeof window === "undefined") return null;
  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return stored === "hu" || stored === "en" ? stored : null;
}

export function detectBrowserLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  return navigator.language.toLowerCase().startsWith("hu") ? "hu" : "en";
}

export function savePreferredLocale(locale: Locale): void {
  if (typeof window !== "undefined") window.localStorage.setItem(LANGUAGE_STORAGE_KEY, locale);
}

export function translate(value: string, locale = activeLocale): string {
  return locale === "hu" ? hungarianEditorial[value] ?? value : englishEditorial[value] ?? translations[value as TranslationKey] ?? value;
}

export function formatCount(value: number, huSingular: string, enSingular: string, locale = activeLocale): string {
  const formatted = new Intl.NumberFormat(locale === "hu" ? "hu-HU" : "en-GB", { maximumFractionDigits: 2 }).format(value);
  if (locale === "hu") return formatted + " " + huSingular;
  return formatted + " " + (value === 1 ? enSingular : enSingular + "s");
}

export function translateDay(value: string, locale = activeLocale): string {
  const days: Record<string, string> = { hétfő: "Monday", kedd: "Tuesday", szerda: "Wednesday", csütörtök: "Thursday", péntek: "Friday", szombat: "Saturday", vasárnap: "Sunday" };
  return locale === "en" ? days[value] ?? value : value;
}

export function translateCategory(value: string, locale = activeLocale): string {
  const categories: Record<string, string> = {
    Mindegy: "All",
    Reggeli: "Breakfast",
    "Csirkés és húsos": "Chicken and meat",
    Halas: "Fish",
    Húsmentes: "Vegetarian",
    "Többadagos ételek": "Meal prep",
    "Batch cooking": "Meal prep",
    "Saját receptek": "Custom recipes"
  };
  if (locale === "en") return categories[value] ?? translate(value, locale);
  const reverse = Object.entries(categories).find(([, translated]) => translated === value)?.[0];
  return reverse ?? value;
}
